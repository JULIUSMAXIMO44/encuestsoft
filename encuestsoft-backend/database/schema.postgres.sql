-- PLANES SaaS
CREATE TABLE IF NOT EXISTS plans (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code VARCHAR(50) NOT NULL UNIQUE,
  name VARCHAR(100) NOT NULL,
  description TEXT,
  price DECIMAL(10,2) DEFAULT 0,
  billing_cycle VARCHAR(20) NOT NULL DEFAULT 'free'
    CHECK (billing_cycle IN ('free','monthly','yearly','one_time')),
  max_forms INTEGER DEFAULT 3,
  max_submissions_per_month INTEGER DEFAULT 500,
  max_storage_mb INTEGER DEFAULT 100,
  max_users INTEGER DEFAULT 1,
  allow_webhooks BOOLEAN DEFAULT FALSE,
  allow_integrations BOOLEAN DEFAULT FALSE,
  allow_custom_branding BOOLEAN DEFAULT FALSE,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- ORGANIZACIONES (TENANTS SaaS)
CREATE TABLE IF NOT EXISTS organizations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid CHAR(36) NOT NULL UNIQUE,
  name VARCHAR(150) NOT NULL,
  slug VARCHAR(150) NOT NULL UNIQUE,
  plan_id INTEGER NOT NULL REFERENCES plans(id),
  logo_url VARCHAR(500),
  primary_color VARCHAR(20) DEFAULT '#4F46E5',
  trial_ends_at TIMESTAMP WITH TIME ZONE,
  subscription_status VARCHAR(20) NOT NULL DEFAULT 'trialing'
    CHECK (subscription_status IN ('trialing','active','past_due','canceled')),
  submissions_used_this_month INTEGER DEFAULT 0,
  storage_used_mb DECIMAL(10,2) DEFAULT 0,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- USUARIOS
CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid CHAR(36) NOT NULL UNIQUE,
  organization_id INTEGER NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  full_name VARCHAR(150) NOT NULL,
  email VARCHAR(150) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(20) NOT NULL DEFAULT 'editor'
    CHECK (role IN ('owner','admin','editor','viewer')),
  avatar_url VARCHAR(500),
  a11y_high_contrast BOOLEAN DEFAULT FALSE,
  a11y_font_scale DECIMAL(3,2) DEFAULT 1.00,
  a11y_reduced_motion BOOLEAN DEFAULT FALSE,
  locale VARCHAR(10) DEFAULT 'es',
  is_active BOOLEAN DEFAULT TRUE,
  email_verified_at TIMESTAMP WITH TIME ZONE,
  last_login_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- FORMULARIOS
CREATE TABLE IF NOT EXISTS forms (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid CHAR(36) NOT NULL UNIQUE,
  organization_id INTEGER NOT NULL REFERENCES organizations(id) ON DELETE CASCADE,
  created_by INTEGER NOT NULL REFERENCES users(id),
  title VARCHAR(200) NOT NULL,
  slug VARCHAR(220) NOT NULL,
  description TEXT,
  status VARCHAR(20) NOT NULL DEFAULT 'draft'
    CHECK (status IN ('draft','published','archived','paused')),
  draft_schema_json JSON,
  is_password_protected BOOLEAN DEFAULT FALSE,
  password_hash VARCHAR(255),
  style_json JSON,
  success_message TEXT,
  error_message TEXT,
  redirect_url VARCHAR(500),
  redirect_delay_seconds INTEGER DEFAULT 0,
  recaptcha_enabled BOOLEAN DEFAULT FALSE,
  recaptcha_version VARCHAR(2) NOT NULL DEFAULT 'v2'
    CHECK (recaptcha_version IN ('v2','v3')),
  notify_email_enabled BOOLEAN DEFAULT TRUE,
  notify_emails TEXT,
  autoresponder_enabled BOOLEAN DEFAULT FALSE,
  autoresponder_subject VARCHAR(255),
  autoresponder_body TEXT,
  autoresponder_field_key VARCHAR(100),
  reference_id_prefix VARCHAR(20) DEFAULT 'REF',
  reference_id_format VARCHAR(50) DEFAULT '{PREFIX}-{YEAR}-{SEQ}',
  allow_prefill_from_url BOOLEAN DEFAULT TRUE,
  custom_attributes_json JSON,
  callback_on_submit VARCHAR(150),
  submission_pdf_enabled BOOLEAN DEFAULT FALSE,
  submission_pdf_template VARCHAR(20) NOT NULL DEFAULT 'simple'
    CHECK (submission_pdf_template IN ('simple','branded')),
  is_multi_step BOOLEAN DEFAULT FALSE,
  allow_multiple_submissions BOOLEAN DEFAULT TRUE,
  limit_one_submission_per_user BOOLEAN DEFAULT FALSE,
  submission_limit INTEGER,
  opens_at TIMESTAMP WITH TIME ZONE,
  closes_at TIMESTAMP WITH TIME ZONE,
  views_count INTEGER DEFAULT 0,
  submissions_count INTEGER DEFAULT 0,
  deleted_at TIMESTAMP WITH TIME ZONE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_forms_org_status ON forms (organization_id, status);

-- CAMPOS DEL FORMULARIO
CREATE TABLE IF NOT EXISTS form_fields (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid CHAR(36) NOT NULL UNIQUE,
  form_id INTEGER NOT NULL REFERENCES forms(id) ON DELETE CASCADE,
  field_key VARCHAR(100) NOT NULL,
  field_type VARCHAR(20) NOT NULL CHECK (field_type IN (
    'text','textarea','email','password','number','phone','date','time','datetime',
    'select','multiselect','radio','checkbox','file','image','rating','recaptcha',
    'heading','paragraph','divider','hidden','signature','address'
  )),
  label VARCHAR(255) NOT NULL,
  placeholder VARCHAR(255),
  help_text VARCHAR(500),
  position INTEGER DEFAULT 0,
  step_number INTEGER DEFAULT 1,
  is_required BOOLEAN DEFAULT FALSE,
  min_length INTEGER,
  max_length INTEGER,
  min_value DECIMAL(15,4),
  max_value DECIMAL(15,4),
  regex_pattern VARCHAR(255),
  validation_message VARCHAR(255),
  options_json JSON,
  default_value VARCHAR(500),
  allowed_file_types VARCHAR(255),
  max_file_size_mb INTEGER DEFAULT 10,
  max_files INTEGER DEFAULT 1,
  aria_label VARCHAR(255),
  aria_describedby_text VARCHAR(500),
  autocomplete_attr VARCHAR(50),
  conditional_logic_json JSON,
  custom_attributes_json JSON,
  width VARCHAR(10) NOT NULL DEFAULT 'full'
    CHECK (width IN ('full','half','third')),
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT uq_form_field_key UNIQUE (form_id, field_key)
);
CREATE INDEX IF NOT EXISTS idx_fields_form_position ON form_fields (form_id, position);

-- ENVÍOS DE FORMULARIOS
CREATE TABLE IF NOT EXISTS form_submissions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid CHAR(36) NOT NULL UNIQUE,
  form_id INTEGER NOT NULL REFERENCES forms(id) ON DELETE CASCADE,
  organization_id INTEGER NOT NULL REFERENCES organizations(id),
  reference_id VARCHAR(80) NOT NULL,
  status VARCHAR(20) NOT NULL DEFAULT 'completed'
    CHECK (status IN ('draft','completed','spam')),
  submitted_by_user_id INTEGER,
  respondent_email VARCHAR(150),
  ip_address VARCHAR(64),
  user_agent VARCHAR(500),
  source_url VARCHAR(500),
  recaptcha_score DECIMAL(3,2),
  pdf_path VARCHAR(500),
  raw_answers_json JSON NOT NULL,
  submitted_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX IF NOT EXISTS idx_submissions_form_date ON form_submissions (form_id, submitted_at);

-- RESPUESTAS NORMALIZADAS (EAV)
CREATE TABLE IF NOT EXISTS submission_answers (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id INTEGER NOT NULL REFERENCES form_submissions(id) ON DELETE CASCADE,
  field_id INTEGER NOT NULL REFERENCES form_fields(id) ON DELETE CASCADE,
  field_key VARCHAR(100) NOT NULL,
  value_text TEXT,
  value_number DECIMAL(15,4),
  value_date TIMESTAMP WITH TIME ZONE
);
CREATE INDEX IF NOT EXISTS idx_answers_field ON submission_answers (field_id);
CREATE INDEX IF NOT EXISTS idx_answers_submission ON submission_answers (submission_id);

-- ARCHIVOS SUBIDOS
CREATE TABLE IF NOT EXISTS submission_files (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  submission_id INTEGER NOT NULL REFERENCES form_submissions(id) ON DELETE CASCADE,
  field_id INTEGER NOT NULL REFERENCES form_fields(id) ON DELETE CASCADE,
  original_name VARCHAR(255),
  stored_path VARCHAR(500) NOT NULL,
  mime_type VARCHAR(100),
  size_bytes INTEGER,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- WEBHOOKS
CREATE TABLE IF NOT EXISTS webhooks (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  form_id INTEGER NOT NULL REFERENCES forms(id) ON DELETE CASCADE,
  url VARCHAR(500) NOT NULL,
  method VARCHAR(10) NOT NULL DEFAULT 'POST' CHECK (method IN ('POST','PUT')),
  headers_json JSON,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS webhook_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  webhook_id INTEGER NOT NULL REFERENCES webhooks(id) ON DELETE CASCADE,
  submission_id INTEGER NOT NULL REFERENCES form_submissions(id) ON DELETE CASCADE,
  attempt INTEGER DEFAULT 1,
  status_code INTEGER,
  success BOOLEAN DEFAULT FALSE,
  response_body TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- INTEGRACIONES DE EMAIL MARKETING
CREATE TABLE IF NOT EXISTS email_integrations (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  form_id INTEGER NOT NULL REFERENCES forms(id) ON DELETE CASCADE,
  provider VARCHAR(20) NOT NULL CHECK (provider IN ('mailchimp','acelle')),
  api_key VARCHAR(255),
  api_url VARCHAR(255),
  list_or_audience_id VARCHAR(150),
  field_mapping_json JSON,
  is_active BOOLEAN DEFAULT TRUE,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

-- AUDITORÍA
CREATE TABLE IF NOT EXISTS audit_logs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  organization_id INTEGER,
  user_id INTEGER,
  action VARCHAR(100) NOT NULL,
  entity_type VARCHAR(50) NOT NULL,
  entity_id INTEGER,
  metadata_json JSON,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);
